#!/usr/bin/env python3
"""The recombination-era thermal history of thermal_init = recfast
(docs/thermal_history.md): x_e(z) and T_gas(z) without any heating from CAMB
(RECFAST).

Without arguments: for the simulation cosmology of cosmo_parameters.f90,
written to data/thermal/recfast_sim_cosmology.txt and, as C++ arrays, to
src/recfast_table.inc (compiled into the code, so a run needs no data file).

With --out FILE: for the cosmology given by --omegam, --omegab, --hubble0
(the params.txt keys of the runtime cosmology; the original's by default),
written to FILE only, with a "# cosmology omegam=.. omegab=.. hubble0=.."
line that radhydro checks against the run's (recfast_table = FILE). Tcmb,
YHe and N_eff stay the code's (2.725 K, 0.24, 3.046).

usage: make_recfast_table.py [--out FILE --omegam 0.305 --omegab 0.048 --hubble0 0.68]
needs `pip install camb`; checked with 1.5.9
"""
import argparse
import os

import camb
import numpy as np

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", help="write only this text table (recfast_table = FILE)")
    ap.add_argument("--omegam", type=float, default=0.27)
    ap.add_argument("--omegab", type=float, default=0.045)
    ap.add_argument("--hubble0", type=float, default=0.70)
    a = ap.parse_args()
    if not a.out and (a.omegam, a.omegab, a.hubble0) != (0.27, 0.045, 0.70):
        ap.error("a non-original cosmology needs --out (the compiled table stays the original's)")
    h, om, ob = a.hubble0, a.omegam, a.omegab
    p = camb.CAMBparams()
    p.set_cosmology(H0=100 * h, ombh2=ob * h * h, omch2=(om - ob) * h * h, TCMB=2.725,
                    YHe=0.24, mnu=0, nnu=3.046)
    p.Reion.Reionization = False  # recombination only: the residual electrons
    bg = camb.get_background(p)
    z = np.concatenate([np.arange(2000, 300, -50.0), np.arange(300, 100, -10.0),
                        np.arange(100, 30, -2.0), np.arange(30, -0.01, -0.5)])
    z[np.abs(z) < 1e-9] = 0.0
    ev = bg.get_background_redshift_evolution(z, ["x_e", "T_b"], format="array")
    if a.out:
        hdr = ("Gas temperature and free-electron fraction x_e = n_e/n_H without any heating (recombination only,\n"
               f"no reionization): CAMB {camb.__version__} with RECFAST: Om = {om}, Ob = {ob}, h = {h},\n"
               "Tcmb = 2.725 K, YHe = 0.24, N_eff = 3.046, no massive neutrinos.\n"
               "tools/thermal/make_recfast_table.py --out; docs/thermal_history.md")
        path = a.out
    else:
        hdr = ("Gas temperature and free-electron fraction x_e = n_e/n_H without any heating (recombination only,\n"
               f"no reionization): CAMB {camb.__version__} with RECFAST for the simulation cosmology of\n"
               "cosmo_parameters.f90: Om = 0.27, Ob = 0.045, h = 0.70, Tcmb = 2.725 K, YHe = 0.24, N_eff = 3.046,\n"
               "no massive neutrinos. tools/thermal/make_recfast_table.py; docs/thermal_history.md")
        path = os.path.join(ROOT, "data", "thermal", "recfast_sim_cosmology.txt")
    with open(path, "w") as f:
        for l in hdr.splitlines():
            f.write("# " + l + "\n")
        if a.out:
            f.write(f"# cosmology omegam={om} omegab={ob} hubble0={h}\n")
        f.write("# z  x_e  T_gas[K]  T_cmb[K]\n")
        for zi, (xe, tb) in zip(z, ev):
            f.write(f"{zi:8.2f} {xe:.6e} {tb:.6e} {2.725 * (1 + zi):.6e}\n")
    if a.out:
        print(len(z), "rows ->", path)
        return
    with open(os.path.join(ROOT, "src", "recfast_table.inc"), "w") as f:
        f.write("// Generated by tools/thermal/make_recfast_table.py; do not edit.\n")
        for l in hdr.splitlines():
            f.write("// " + l + "\n")
        f.write("// Rows in increasing z: {z, x_e, T_gas [K]}.\n")
        f.write(f"constexpr int kRecfastRows = {len(z)};\n")
        f.write("constexpr double kRecfast[kRecfastRows][3] = {\n")
        for zi, (xe, tb) in sorted(zip(z, ev), key=lambda r: r[0]):
            f.write(f"    {{{zi:.2f}, {xe:.6e}, {tb:.6e}}},\n")
        f.write("};\n")
    print(len(z), "rows")


if __name__ == "__main__":
    main()
